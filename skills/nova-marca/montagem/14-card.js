// Garoa Starter · receita 14: Card (usa o Button). EXEMPLO = textos de exemplo do negócio.
const EXEMPLO = { titulo: 'Design system Garoa', corpo: 'Tokens, componentes e regras para gerar telas consistentes com IA.', acao: 'Ver case' };
const pg = await pagina('22 · Card');
apagarSeExiste(pg, 'Card');
const K = 'C:card/';
const c = figma.createComponent(); c.name = 'Card';
layout(c, 'V', [K + 'padding', K + 'padding'], K + 'gap', false);
c.counterAxisSizingMode = 'FIXED'; c.resize(400, c.height);
raio(c, K + 'radius'); fundo(c, K + 'bg'); borda(c, K + 'border', K + 'border-width', true);
const sombra = _fx.find(x => x.name === 'shadow/100'); if (sombra) await c.setEffectStyleIdAsync(sombra.id);
const tit = await texto('Card/Title', 'Heading/H4', 'CS:color/text/primary', EXEMPLO.titulo);
const corpo = await texto('Card/Body', 'Body/SM/Regular', 'CS:color/text/primary', EXEMPLO.corpo);
const acao = (await varianteDe('Button', 'variant=primary, state=default')).createInstance(); acao.name = 'Card/Action';
ajustar(acao, { label: EXEMPLO.acao, iconLeft: false, iconRight: false });
c.appendChild(tit); c.appendChild(corpo); c.appendChild(acao);
for (const n of [tit, corpo, acao]) n.layoutSizingHorizontal = 'FILL';
tit.textAutoResize = 'HEIGHT'; corpo.textAutoResize = 'HEIGHT';
const ctrl = acao.findOne(n => n.name === 'Button/Control'); if (ctrl) ctrl.layoutSizingHorizontal = 'FILL';
const pT = c.addComponentProperty('title', 'TEXT', EXEMPLO.titulo);
const pB = c.addComponentProperty('body', 'TEXT', EXEMPLO.corpo);
const pVT = c.addComponentProperty('showTitle', 'BOOLEAN', true);
const pVA = c.addComponentProperty('showAction', 'BOOLEAN', true);
tit.componentPropertyReferences = { characters: pT, visible: pVT };
corpo.componentPropertyReferences = { characters: pB };
acao.componentPropertyReferences = { visible: pVA };
c.description = 'Card (superfície elevada) com título, texto e botão opcionais. Sombra shadow/100, sem recortar conteúdo. Largura livre: os filhos preenchem.';
c.x = 0; c.y = 0;
await c.screenshot({ scale: 1 });
return { componente: c.name, tamanho: [c.width, Math.round(c.height)] };
